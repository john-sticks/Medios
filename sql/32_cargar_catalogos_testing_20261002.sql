CREATE PROCEDURE medios_cargar_catalogos_20261002()
BEGIN
    DECLARE division_id INT;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;
    IF DATABASE() <> 'medios' OR @@SESSION.foreign_key_checks <> 1 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Base incorrecta o foreign_key_checks desactivado';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.TABLES
        WHERE TABLE_SCHEMA='medios' AND ENGINE='InnoDB' AND TABLE_NAME IN
        ('delegaciones','partidos_prometheus','caratulas_quiron','modalidades_quiron')) <> 4 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Se requieren las cuatro tablas InnoDB';
    END IF;
    IF (SELECT COUNT(*) FROM delegaciones) <> 1
        OR (SELECT COUNT(*) FROM delegaciones WHERE HEX(Nombre)='446976697369C3B36E204D6564696F73' AND DelegacionPrometheusId IS NULL) <> 1 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Delegaciones cambiaron: revisar antes de importar';
    END IF;
    IF EXISTS(SELECT 1 FROM caratulas_quiron) OR EXISTS(SELECT 1 FROM modalidades_quiron)
        OR EXISTS(SELECT 1 FROM partidos_prometheus WHERE DelegacionId IS NOT NULL) THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Ya hay catalogos o asignaciones: no sobrescribir';
    END IF;
    IF (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='medios'
        AND TABLE_NAME IN ('caratulas_quiron','modalidades_quiron')
        AND COLUMN_NAME='id' AND EXTRA LIKE '%auto_increment%') <> 2 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Aplicar primero AUTO_INCREMENT a ambos catalogos';
    END IF;
    IF (SELECT COUNT(*) FROM partidos_prometheus) <> 135
        OR (SELECT COUNT(*) FROM partidos_prometheus p JOIN tmp_medios_partidos t ON t.Id=p.id
            JOIN tmp_medios_catalogos a ON a.Tipo='superintendencia' AND a.Id=t.AreaId
            JOIN superintendencias_prometheus pa ON pa.id=p.superintendencia_id
            WHERE HEX(p.nombre)=HEX(t.Nombre) AND HEX(pa.nombre)=HEX(a.Nombre)
            AND p.delegacion_id=t.CatalogoId) <> 135 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Los partidos productivos difieren del snapshot';
    END IF;
    IF (SELECT COUNT(*) FROM delegaciones_prometheus) <> 21
        OR (SELECT COUNT(*) FROM delegaciones_prometheus d JOIN tmp_medios_catalogos t
            ON t.Tipo='delegacion' AND t.Id=d.id WHERE HEX(d.nombre)=HEX(t.Nombre)) <> 21 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='El catalogo de delegaciones difiere del snapshot';
    END IF;
    -- MySQL no permite abrir dos veces una tabla temporal en una sentencia.
    -- Mantener separadas estas comprobaciones del catalogo compartido.
    IF (SELECT COUNT(*) FROM tmp_medios_catalogos t
            WHERE t.Tipo='superintendencia' AND
                (SELECT COUNT(*) FROM superintendencias_prometheus a
                 WHERE HEX(a.nombre)=HEX(t.Nombre))=1) <> 16 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Falta un match unico por superintendencia';
    END IF;
    SELECT Id INTO division_id FROM delegaciones LIMIT 1;
    START TRANSACTION;
    INSERT INTO delegaciones (Nombre,AreaResponsabilidadId,DelegacionPrometheusId,Activa)
        SELECT d.Nombre,pa.id,d.CatalogoId,d.Activa
        FROM tmp_medios_delegaciones d
        LEFT JOIN tmp_medios_catalogos a ON a.Tipo='superintendencia' AND a.Id=d.AreaId
        LEFT JOIN superintendencias_prometheus pa ON HEX(pa.nombre)=HEX(a.Nombre)
        WHERE d.SourceId <> 38 ORDER BY d.SourceId;
    UPDATE partidos_prometheus p
        JOIN tmp_medios_partidos t ON t.Id=p.id
        JOIN tmp_medios_delegaciones sd ON sd.SourceId=t.SourceDelegacionId
        JOIN delegaciones d ON
            (sd.SourceId=38 AND d.Id=division_id)
            OR (sd.CatalogoId IS NOT NULL AND d.DelegacionPrometheusId=sd.CatalogoId)
            OR (sd.SourceId<>38 AND sd.CatalogoId IS NULL
                AND d.DelegacionPrometheusId IS NULL AND HEX(d.Nombre)=HEX(sd.Nombre))
        SET p.DelegacionId=d.Id;
    INSERT INTO caratulas_quiron(id,nombre,consumable,calificable)
        SELECT Id,Nombre,Consumable,Calificable FROM tmp_medios_caratulas ORDER BY Id;
    INSERT INTO modalidades_quiron(id,nombre,caratula_id)
        SELECT Id,Nombre,CaratulaId FROM tmp_medios_modalidades ORDER BY Id;
    IF (SELECT COUNT(*) FROM delegaciones) <> 23
        OR (SELECT COUNT(*) FROM partidos_prometheus WHERE DelegacionId IS NOT NULL) <> 135
        OR (SELECT COUNT(*) FROM caratulas_quiron) <> 28
        OR (SELECT COUNT(*) FROM modalidades_quiron) <> 86 THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Conteos inesperados; carga revertida';
    END IF;
    COMMIT;
END//
